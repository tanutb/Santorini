/** Bundle only the Three.js classes the renderer imports into web/vendor/three.js (minified, tree-shaken). */
import { readFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { build } from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ADDONS = {
  RoundedBoxGeometry: 'three/addons/geometries/RoundedBoxGeometry.js',
  RoomEnvironment: 'three/addons/environments/RoomEnvironment.js',
  mergeGeometries: 'three/addons/utils/BufferGeometryUtils.js',
};
const names = new Set();
for (const file of ['three-board.js', 'island-models.js']) {
  const source = await readFile(path.join(root, 'web', file), 'utf8');
  for (const match of source.matchAll(/import\s*\{([^}]*)\}\s*from\s*'\.\/vendor\/three\.js'/g)) {
    for (const name of match[1].split(',').map(part => part.trim()).filter(Boolean)) names.add(name);
  }
}
const core = [...names].filter(name => !ADDONS[name]).sort();
const lines = [`export { ${core.join(', ')} } from 'three';`];
for (const name of [...names].filter(name => ADDONS[name]).sort()) lines.push(`export { ${name} } from '${ADDONS[name]}';`);
const { version } = JSON.parse(await readFile(path.join(root, 'node_modules/three/package.json'), 'utf8'));
await mkdir(path.join(root, 'web/vendor'), { recursive: true });
const result = await build({
  stdin: { contents: lines.join('\n'), resolveDir: root, loader: 'js', sourcefile: 'three-entry.js' },
  bundle: true, format: 'esm', minify: true, target: 'es2020', legalComments: 'none', metafile: true,
  banner: { js: `/* three.js ${version} (MIT License, https://github.com/mrdoob/three.js). Generated by scripts/vendor-three.mjs; do not edit. */` },
  outfile: path.join(root, 'web/vendor/three.js'),
});
const bytes = Object.values(result.metafile.outputs)[0].bytes;
console.log(`web/vendor/three.js: ${names.size} exports, ${(bytes / 1024).toFixed(0)} KiB`);
